#pragma once

/*! \file calc.hpp
 *  \brief Library with functions for calculating stuff.
 */

/*! \brief Convert Celsius degree to Fahrenheit degree.
 *  \param[in] Celsius Temperature in Celsius.
 *  \returns Temperature in Fahrenheit.
 */
double celsius_to_fahrenheit(double celsius);

/*! \brief Convert Fahrenheit degree to Celsius degree.
 *  \param[in] Celsius Temperature in Fahrenheit.
 *  \returns Temperature in Celsius.
 */
double fahrenheit_to_celsius(double fahrenheit);
